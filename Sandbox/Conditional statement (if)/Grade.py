score = int(input("Enter your score: "))
if score >= 90:
    print("Your grade is A1") 
elif score >= 80:
    print("Your grade is A2") 
elif score >= 70:
    print("Your grade is B1") 
elif score >= 60:
    print("Your grade is B2") 
elif score >= 50:
    print("Your grade is C")
else: 
    print("Failed") 